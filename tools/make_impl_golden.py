"""Generate implementation-produced golden cases (spec/10): `create`, `mutate`, `diversity`,
`population` and `modify`.

Generated by the Python implementation; the C++ implementation must reproduce every file
byte for byte. Run from the repository root with the package installed:

    python/.venv/bin/python tools/make_impl_golden.py [create|mutate|diversity|population|modify|all]
"""
import json
import os
import sys
import tempfile
from pathlib import Path

from jneuro import DepthType, Net, Priority
from jneuro.jnet import net_to_bytes
from jneuro.mutate import Profile, inject_diversity, mutate
from jneuro.population import Population
from jneuro.rng import Rng
import struct

ROOT = os.path.join("tests", "golden")
PHASES = ["op_change_max_pct", "edit_max_pct", "growth_max_pct", "removal_max_pct",
          "depth_shift_max_pct"]


def write(sub, name, case):
    os.makedirs(os.path.join(ROOT, sub), exist_ok=True)
    with open(os.path.join(ROOT, sub, name + ".json"), "w") as f:
        json.dump(case, f, indent=1)
        f.write("\n")


def make_create():
    params = [(1, 1, "U16", 3), (1, 4, "U32", 5), (3, 2, "U64", 3), (5, 3, "U32", 5),
              (7, 2, "U16", 3), (30, 3, "U32", 3), (40, 1, "U64", 5), (6, 6, "U16", 7)]
    for i, (n_in, n_out, dt, q) in enumerate(params):
        for seed, mix, run in ((0, 2, 3), (77, 0 if i % 2 == 0 else 3, 0 if i % 2 == 0 else 2), (5, 2, 1)):
            prio = list(Priority)[(i + seed) % 3].name
            net = Net.create(n_in, n_out, DepthType[dt], q, Priority[prio], Rng(seed), mix, run)
            write("create", f"create_{n_in}x{n_out}_{dt}_q{q}_s{seed}_p{mix}_r{run}",
                  {"kind": "create", "seed": seed, "n_inputs": n_in, "n_outputs": n_out,
                   "depth_type": dt, "in_qty_max": q, "priority": prio, "path_mix": mix,
                   "max_run": run, "expected_jnet": net_to_bytes(net).hex()})


def profile_variants():
    def zero():
        p = Profile.default()
        for f in PHASES:
            p.overall[f] = 0.0
        return p

    out = {"default": Profile.default()}
    fold = Profile.default()
    fold.overall["constant_folding"] = "on"
    out["fold"] = fold
    exact = Profile.default()
    exact.overall["growth_budget"] = "exact"
    exact.overall["growth_max_pct"] = 6.0
    out["exact_growth"] = exact
    taps = Profile.default()
    taps.overall["growth_max_pct"] = 30.0
    taps.overall["add_method_weights"].update({"v_tap": 30, "s_tap": 30, "m_tap": 30})
    out["taps"] = taps
    clone = Profile.default()
    clone.overall["growth_max_pct"] = 30.0
    clone.overall["add_method_weights"].update({"m_clone": 60})
    out["clone"] = clone
    mid = Profile.default()
    mid.overall["growth_max_pct"] = 30.0
    mid.overall["insert_depth"] = "midpoint"
    mid.overall["add_method_weights"].update({"v_tap": 20, "s_tap": 20, "m_tap": 20, "m_clone": 20})
    out["midpoint"] = mid
    gated = Profile.default()
    gated.overall["growth_max_pct"] = 30.0
    gated.overall["growth_net_prob"] = 0.5
    out["gated"] = gated
    biased = Profile.default()
    biased.overall["edit_max_pct"] = 40.0
    biased.overall["slot_edit"] = "biased"
    biased.overall["prune"] = "any"
    biased.overall["insert_depth"] = "uniform"
    out["biased"] = biased
    heavy = Profile.default()
    for f in PHASES:
        heavy.overall[f] = 40.0
    heavy.overall["min_age_for_removal"] = 1
    out["heavy"] = heavy
    for f in PHASES:
        p = zero()
        p.overall[f] = 100.0
        p.overall["min_age_for_removal"] = 0
        out["only_" + f.replace("_max_pct", "")] = p
    for m in ("slot_fill", "v_insert", "s_insert", "m_after_m"):
        p = zero()
        p.overall["growth_max_pct"] = 100.0
        p.overall["add_method_weights"] = {k: (1.0 if k == m else 0.0)
                                           for k in ("slot_fill", "v_insert", "s_insert", "m_after_m")}
        out["growth_" + m] = p
    capped = Profile.default()
    for f in PHASES:
        capped.overall[f] = 60.0
    capped.apply_patch({"v": {"growth_max_pct": 5.0, "sigma_weight": 0.5},
                        "s": {"edit_max_pct": 0.0}, "m": {"removal_max_pct": 100.0}})
    capped.overall["depth_shift_mode"] = "center"
    out["per_type_caps_center"] = capped
    return out


def make_mutate():
    # Parent genomes: grown from minimal nets with a heavy profile so all neuron types appear.
    grow = Profile.default()
    for f in PHASES:
        grow.overall[f] = 35.0
    grow.overall["min_age_for_removal"] = 2
    parents = []
    for i, (n_in, n_out, dt, q) in enumerate([(3, 2, "U16", 3), (6, 1, "U32", 5), (1, 2, "U64", 3),
                                              (9, 2, "U32", 3)]):
        r = Rng(500 + i)
        net = Net.create(n_in, n_out, DepthType[dt], q, Priority.SPEED, r, [2, 0, 3, 2][i], [3, 0, 2, 3][i])
        for gen in range(1, 13):
            net = mutate(net, grow, gen, r)
        parents.append(net)
    for pname, prof in profile_variants().items():
        for pi, parent in enumerate(parents):
            seed = 31 * pi + len(pname)
            gen = 20
            child = mutate(parent, prof, gen, Rng(seed))
            write("mutate", f"mutate_{pname}_p{pi}",
                  {"kind": "mutate", "seed": seed, "generation": gen,
                   "jnet": net_to_bytes(parent).hex(), "profile": prof.to_dict(),
                   "expected_jnet": net_to_bytes(child).hex()})


def make_mutate_mix():
    """Small path_mix 1 net where each mix-rule check of spec/06 can trigger."""
    from jneuro import AggOp, Inversion, MNeuron, Node, SNeuron, VNeuron, VOp
    d = DepthType.U16.d_max
    nodes = [Node(0, 0, 0), Node(1, 0, d, MNeuron(AggOp.MAX, [3, 4, None])),
             Node(2, 0, 100, VNeuron(0, Inversion.NONE, VOp.MUL, 1.0)),
             Node(3, 0, 200, SNeuron(2, AggOp.MEAN, 1)), Node(4, 0, 200, SNeuron(2, AggOp.MEAN, 1))]
    net = Net(Priority.SPEED, DepthType.U16, 3, 1, 1, nodes, 5, 1, 0)
    net.validate()
    fill = {"slot_fill": 1, "v_insert": 0, "s_insert": 0, "m_after_m": 0}
    for name, over in [("bypass", {"removal_max_pct": 100.0, "min_age_for_removal": 0}),
                       ("rewire", {"edit_max_pct": 100.0, "rewire_prob": 1.0}),
                       ("slot_connect", {"edit_max_pct": 100.0, "rewire_prob": 0.0, "sigma_slots": 3.0}),
                       ("slot_fill", {"growth_max_pct": 100.0, "add_method_weights": fill})]:
        prof = Profile.default()
        for f in PHASES:
            prof.overall[f] = 0.0
        prof.overall.update(over)
        for seed in range(3):
            child = mutate(net, prof, 10, Rng(seed))
            write("mutate", f"mutate_mix_{name}_{seed}",
                  {"kind": "mutate", "seed": seed, "generation": 10,
                   "jnet": net_to_bytes(net).hex(), "profile": prof.to_dict(),
                   "expected_jnet": net_to_bytes(child).hex()})


def make_diversity():
    grow = Profile.default()
    for f in PHASES:
        grow.overall[f] = 35.0
    for i, (pct, sigma) in enumerate([(0.0, 1.0), (25.0, 1.0), (60.0, 0.5), (100.0, 3.0)]):
        r = Rng(900 + i)
        net = Net.create(5, 2, DepthType.U32, 5, Priority.SPEED, r)
        for gen in range(1, 10):
            net = mutate(net, grow, gen, r)
        seed = 40 + i
        child = inject_diversity(net, pct, Rng(seed), sigma)
        write("diversity", f"diversity_{i}", {"kind": "diversity", "seed": seed, "pct": pct,
                                              "sigma_reset": sigma, "jnet": net_to_bytes(net).hex(),
                                              "expected_jnet": net_to_bytes(child).hex()})


def make_population():
    def bits(x):
        return struct.pack(">d", x).hex()

    def heavy(mode):
        p = Profile.default()
        for f in PHASES:
            p.overall[f] = 45.0
        p.overall["rng_mode"] = mode
        p.overall["min_age_for_removal"] = 1
        p.overall["growth_gen_prob"] = 0.5
        p.overall["growth_net_prob"] = 0.7
        return p

    for i, dt in enumerate(["U16", "U32", "U64"]):
        n_in, n_out, q = 2 + i, 1 + i, [3, 5, 3][i]
        pop = Population(DepthType[dt], q, n_in, n_out, list(Priority)[i], seed=1000 + i)
        ids = pop.create(4)                                   # fresh seeds, recorded in the log
        ids += pop.create(2, rng_mode="shared")
        for gen in range(6):
            for nid in list(pop.ids()):
                pop.mutate(nid, heavy("fresh" if (nid + gen) % 2 else "shared"))
            for nid in pop.ids()[:-6]:
                pop.remove(nid)
            pop.inject_diversity(pop.ids()[0], 40.0, 1.5, "shared")
            pop.next_generation()
        pop.clone(pop.ids()[1])
        rows = [[(r * 0.75 - 1.0) * (k + 1) for k in range(n_in)] for r in range(12)]
        res = pop.evaluate(rows)
        with tempfile.TemporaryDirectory() as tmp:
            pop.save(Path(tmp) / "pop.jpnet")
            jpnet = (Path(tmp) / "pop.jpnet").read_bytes().hex()
        write("population", f"population_{dt}", {
            "kind": "population", "log": json.loads(pop.run_log()),
            "expected": {"generation": pop.generation, "ids": pop.ids(),
                         "jnets": {str(k): net_to_bytes(pop.get(k)).hex() for k in pop.ids()}},
            "save": {"name": "pop", "jpnet": jpnet},
            "evaluate": {"inputs": [[bits(x) for x in r] for r in rows],
                         "outputs": {str(k): [[bits(y) for y in r] for r in v] for k, v in res.items()}}})


def make_modify():
    """spec/12: every add/remove operation on grown nets, plus nets whose receivers are all `min`."""
    from jneuro import modify
    grow = Profile.default()
    for f in PHASES:
        grow.overall[f] = 35.0
    grow.overall["min_age_for_removal"] = 2
    nets = []
    for i, (n_in, n_out, dt, q, mix, run) in enumerate([(3, 2, "U16", 3, 2, 3), (6, 3, "U32", 5, 1, 2),
                                                         (1, 2, "U64", 3, 2, 0), (9, 2, "U32", 3, 0, 1),
                                                         (4, 4, "U16", 7, 3, 3)]):
        r = Rng(700 + i)
        net = Net.create(n_in, n_out, DepthType[dt], q, Priority.SPEED, r, mix, run)
        for gen in range(1, 15):
            net = mutate(net, grow, gen, r)
        nets.append((f"g{i}", net))
    nets.append(("min1x3", Net.create(1, 3, DepthType.U16, 3, Priority.MEMORY, Rng(3))))
    nets.append(("min5x2", Net.create(5, 2, DepthType.U32, 5, Priority.BALANCED, Rng(4), 2, 1)))

    def case(name, net, op, args, child):
        write("modify", f"modify_{name}_{op}" + "".join(f"_{k[0]}{int(v)}" for k, v in args.items()),
              {"kind": "modify", "op": op, "args": args, "jnet": net_to_bytes(net).hex(),
               "expected_jnet": net_to_bytes(child).hex()})

    for name, net in nets:
        for pos in sorted({0, net.n_inputs}):
            for active in (False, True):
                args = {"position": pos, "active": active, "generation": 30}
                case(name, net, "add_input", args, modify.add_input(net, pos, active, 30))
        args = {"source": net.n_outputs - 1, "position": 0, "generation": 30}
        case(name, net, "add_output_clone", args, modify.add_output_clone(net, net.n_outputs - 1, 0, 30))
        args = {"seed": 11, "position": net.n_outputs, "generation": 30}
        case(name, net, "add_output_fresh", args, modify.add_output_fresh(net, Rng(11), net.n_outputs, 30))
        for idx in sorted({0, net.n_inputs - 1}) if net.n_inputs > 1 else []:
            case(name, net, "remove_input", {"index": idx}, modify.remove_input(net, idx))
        for idx in sorted({0, net.n_outputs - 1}) if net.n_outputs > 1 else []:
            case(name, net, "remove_output", {"index": idx}, modify.remove_output(net, idx))


if __name__ == "__main__":
    what = sys.argv[1] if len(sys.argv) > 1 else "all"
    if what in ("create", "all"):
        make_create()
    if what in ("mutate", "all"):
        make_mutate()
        make_mutate_mix()
    if what in ("diversity", "all"):
        make_diversity()
    if what in ("population", "all"):
        make_population()
    if what in ("modify", "all"):
        make_modify()
